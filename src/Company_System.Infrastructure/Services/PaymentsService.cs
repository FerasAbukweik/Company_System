using System.Linq.Expressions;
using HR_System.Core.Enums;
using System.Net;
using HR_System.Core.Abstraction.RepositoryContracts;
using HR_System.Core.Abstraction.ServiceContracts;
using HR_System.Core.Domain.Entities;
using HR_System.Core.DTO.Payments;
using HR_System.Core.Result;
using Microsoft.Data.SqlClient;
using Microsoft.EntityFrameworkCore;

namespace HR_System.Infrastructure.Services;

public class PaymentsService(
    IPaymentsRepository paymentsRepository,
    IApplicationUsersRepository usersRepository,
    IDailyWorkRecordsRepository dailyWorkRecordsRepository) : IPaymentsService
{
    public async Task<Result<int>> GenerateMonthlyPaymentsAsync(DateOnly month, CancellationToken cancellationToken = default)
    {
        if (month.Day != 1 || month == new DateOnly(9999, 12, 1))
            return Result<int>.Failure("The payroll period must start on the first day of the month", HttpStatusCode.BadRequest);

        var employees = await usersRepository.FilterAsync(
            user => user.OrganizationHierarchy != null && user.OrganizationHierarchy.IsActive && user.HourlyRate > 0,
            cancellationToken: cancellationToken);

        var workedHours = await dailyWorkRecordsRepository.GetWorkedHoursAsync(
            month, month.AddMonths(1), cancellationToken);

        var existing = await paymentsRepository.FilterAsync(
            payment => payment.Year == month.Year && payment.Month == month.Month,
            cancellationToken: cancellationToken);
        var paidEmployees = existing.Select(payment => payment.UserId).ToHashSet();
        var created = 0;

        foreach (var employee in employees)
        {
            if (paidEmployees.Contains(employee.Id)) continue;

            var hours = workedHours.GetValueOrDefault(employee.Id);
            var amount = decimal.Round(hours * employee.HourlyRate!.Value, 2, MidpointRounding.AwayFromZero);
            if (amount <= 0) continue;

            paymentsRepository.Add(new Payment()
            {
                UserId = employee.Id,
                Year = month.Year,
                Month = month.Month,
                PaidAmount = amount,
                PaymentDate = null,
                State = PaymentStateEnum.Pending
            }, cancellationToken);

            created++;
        }

        if (created == 0) return Result<int>.Success(0);

        try
        {
            // A single save is atomic. The unique employee/year/month index also protects multiple API instances.
            if (!await paymentsRepository.SaveChangesAsync(cancellationToken))
                return Result<int>.Failure("Failed to generate monthly payments");
        }
        catch (DbUpdateException exception) when (exception.InnerException is SqlException { Number: 2601 or 2627 })
        {
            // The worker retries in a fresh scope, where the competing instance's rows will be visible.
            return Result<int>.Failure("Monthly payments were generated by another instance; retry the remaining records", HttpStatusCode.Conflict);
        }

        return Result<int>.Success(created);
    }

    public async Task<Result<PaymentDTO>> UpdateStateAsync(
        Guid paymentId,
        PaymentStateEnum state,
        CancellationToken cancellationToken = default)
    {
        if (!Enum.IsDefined(state))
            return Result<PaymentDTO>.Failure("Invalid payment state", HttpStatusCode.BadRequest);

        var payment = await paymentsRepository.UpdateStateAsync(paymentId, state, cancellationToken);
        if (payment is null)
            return Result<PaymentDTO>.Failure("Payment not found", HttpStatusCode.NotFound);

        try
        {
            if (!await paymentsRepository.SaveChangesAsync(cancellationToken))
                return Result<PaymentDTO>.Failure("Failed to update payment state");
        }
        catch (DbUpdateConcurrencyException)
        {
            return Result<PaymentDTO>.Failure("Payment changed; refresh and retry", HttpStatusCode.Conflict);
        }

        return Result<PaymentDTO>.Success(payment.ToDTO());
    }

    public async Task<Result<IReadOnlyList<PaymentDTO>>> GetUserPaymentsAsync(
        Guid userId,
        int year,
        PaymentStateEnum? state = null,
        CancellationToken cancellationToken = default)
    {
        if (userId == Guid.Empty || year is < 1 or > 9999)
            return Result<IReadOnlyList<PaymentDTO>>.Failure("Invalid employee or year", HttpStatusCode.BadRequest);

        if (state.HasValue && !Enum.IsDefined(state.Value))
            return Result<IReadOnlyList<PaymentDTO>>.Failure("Invalid payment state", HttpStatusCode.BadRequest);

        var payments = await paymentsRepository.FilterAsync(
            p => p.UserId == userId && p.Year == year && (!state.HasValue || p.State == state.Value),
            orderBy: p => p.Year * 12 + p.Month,
            orderByDesc: true,
            cancellationToken: cancellationToken);

        return Result<IReadOnlyList<PaymentDTO>>.Success(payments.Select(p => p.ToDTO()).ToList());
    }


    public async Task<Result<UserPaymentPageDTO>> GetUserPaymentPageAsync(Guid userId, UserPaymentQueryDTO query, CancellationToken cancellationToken = default)
    {
        if (userId == Guid.Empty || query.Year is < 1 or > 9999 || query.Taken < 0 || query.SectionSize < 1 ||
            (query.State.HasValue && !Enum.IsDefined(query.State.Value)))
            return Result<UserPaymentPageDTO>.Failure("Invalid payment filters or page size", HttpStatusCode.BadRequest);

        var total = await paymentsRepository.CountAsync(payment => payment.UserId == userId && payment.Year == query.Year &&
            (!query.State.HasValue || payment.State == query.State.Value), cancellationToken);
        var payments = await paymentsRepository.FilterAsync(
            payment => payment.UserId == userId && payment.Year == query.Year && (!query.State.HasValue || payment.State == query.State.Value),
            orderBy: payment => payment.Year * 12 + payment.Month,
            orderByDesc: true,
            skip: query.Taken,
            take: query.SectionSize,
            cancellationToken: cancellationToken);
        return Result<UserPaymentPageDTO>.Success(new UserPaymentPageDTO
        {
            Items = payments.Select(payment => payment.ToDTO()).ToList(),
            TotalCount = total
        });
    }

    public async Task<Result<UserPaymentOverviewDTO>> GetUserOverviewAsync(Guid userId, CancellationToken cancellationToken = default)
    {
        if (userId == Guid.Empty)
            return Result<UserPaymentOverviewDTO>.Failure("Invalid employee", HttpStatusCode.BadRequest);

        var today = DateOnly.FromDateTime(DateTime.UtcNow);
        var summary = await paymentsRepository.GetUserSummaryAsync(userId, today.Year, cancellationToken);
        var paidLeaveDays = await dailyWorkRecordsRepository.CountPaidLeaveDaysAsync(userId, new DateOnly(today.Year, 1, 1), today, cancellationToken);
        var latest = await paymentsRepository.FilterAsync(
            payment => payment.UserId == userId && payment.State == PaymentStateEnum.Approved,
            orderBy: payment => payment.PaymentDate,
            orderByDesc: true,
            take: 1,
            cancellationToken: cancellationToken);

        return Result<UserPaymentOverviewDTO>.Success(new UserPaymentOverviewDTO
        {
            ApprovedAmount = summary.ApprovedAmount,
            PendingAmount = summary.PendingAmount,
            PaidLeaveDays = paidLeaveDays,
            LatestApproved = latest.FirstOrDefault()?.ToDTO()
        });
    }

    public async Task<Result<AdminPaymentSummaryDTO>> GetAdminSummaryAsync(CancellationToken cancellationToken = default)
    {
        return Result<AdminPaymentSummaryDTO>.Success(await paymentsRepository.GetAdminSummaryAsync(cancellationToken));
    }

    public async Task<Result<AdminPaymentPageDTO>> GetPaymentsAsync(PaymentQueryDTO query, CancellationToken cancellationToken = default)
    {
        if (query.Year is < 1 or > 9999 || query.Month is < 1 or > 12 || query.Taken < 0 || query.SectionSize < 1 ||
            query.FullName?.Length > 100 || (query.State.HasValue && !Enum.IsDefined(query.State.Value)))
            return Result<AdminPaymentPageDTO>.Failure("Invalid payment filters", HttpStatusCode.BadRequest);

        var name = query.FullName?.Trim().ToUpperInvariant();
        Expression<Func<Payment, bool>> predicate = payment => payment.Year == query.Year && (!query.Month.HasValue || payment.Month == query.Month) &&
            (!query.State.HasValue || payment.State == query.State) && (!query.UserId.HasValue || payment.UserId == query.UserId) &&
            (!query.HistoryOnly || payment.State != PaymentStateEnum.Pending) &&
            (string.IsNullOrEmpty(name) || (payment.User != null && payment.User.FullName.ToUpper().Contains(name)));
        var count = await paymentsRepository.CountAsync(predicate, cancellationToken);
        var payments = await paymentsRepository.FilterAsync(predicate,
            include: [payment => payment.User!, payment => payment.User!.Image],
            orderBy: payment => payment.Year * 12 + payment.Month,
            orderByDesc: true,
            skip: query.Taken,
            take: query.SectionSize,
            cancellationToken: cancellationToken);
        return Result<AdminPaymentPageDTO>.Success(new AdminPaymentPageDTO
        {
            Items = payments.Select(payment => payment.ToDTO()).ToList(),
            TotalCount = count
        });
    }

    public async Task<Result<IReadOnlyList<PaymentDTO>>> UpdateStatesAsync(IReadOnlyList<Guid> paymentIds, PaymentStateEnum state, CancellationToken cancellationToken = default)
    {
        if (paymentIds.Count is < 1 or > 100 || paymentIds.Any(id => id == Guid.Empty) ||
            paymentIds.Distinct().Count() != paymentIds.Count || state is not (PaymentStateEnum.Approved or PaymentStateEnum.Rejected))
            return Result<IReadOnlyList<PaymentDTO>>.Failure("Select up to 100 unique payments and approve or reject them", HttpStatusCode.BadRequest);

        var payments = await paymentsRepository.FilterAsync(p => paymentIds.Contains(p.Id), cancellationToken: cancellationToken);
        if (payments.Count != paymentIds.Count)
            return Result<IReadOnlyList<PaymentDTO>>.Failure("One or more payments were not found", HttpStatusCode.NotFound);
        if (payments.Any(payment => payment.State != PaymentStateEnum.Pending))
            return Result<IReadOnlyList<PaymentDTO>>.Failure("Only pending payments can be decided in a batch", HttpStatusCode.Conflict);

        var updated = new List<PaymentDTO>();
        foreach (var payment in payments)
        {
            paymentsRepository.SetState(payment, state);
            updated.Add(payment.ToDTO());
        }

        try
        {
            if (!await paymentsRepository.SaveChangesAsync(cancellationToken))
                return Result<IReadOnlyList<PaymentDTO>>.Failure("Failed to save payment decisions");
        }
        catch (DbUpdateConcurrencyException)
        {
            return Result<IReadOnlyList<PaymentDTO>>.Failure("A payment changed; refresh and retry", HttpStatusCode.Conflict);
        }

        return Result<IReadOnlyList<PaymentDTO>>.Success(updated);
    }

}
